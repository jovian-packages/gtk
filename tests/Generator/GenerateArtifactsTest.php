<?php

declare(strict_types=1);

it('emits a GtkButton DTO that aliases the extension and exposes new()', function (): void {
    $path = dirname(__DIR__, 2) . '/src/Gtk/GtkButton.php';
    expect(is_file($path))->toBeTrue();
    $text = file_get_contents($path);
    expect($text)->toContain('GENERATED by scripts/generate.php')
        ->and($text)->toContain('use Gtk\\Gtk\\GtkButton\\GtkButton as ExtGtkButton')
        ->and($text)->toContain('public static function new()')
        ->and($text)->toContain('ExtGtkButton::new_()')
        ->and($text)->toContain("Bridge::connect(\$this->handle, 'clicked'");
});

it('names helpers from the GIR c:identifier', function (): void {
    $path = dirname(__DIR__, 2) . '/src/Helpers/gtk-button.php';
    expect(is_file($path))->toBeTrue();
    $text = file_get_contents($path);
    expect($text)->toContain('function gtk_button_set_label(int $handle, string $label): void')
        ->and($text)->toContain('function gtk_button_new(): int')
        ->and($text)->toContain('ExtGtkButton::setLabel($handle, $label)');
});

it('emits a GType-to-PHP-class map keyed by glib:type-name', function (): void {
    $path = dirname(__DIR__, 2) . '/src/Runtime/GeneratedTypeMap.php';
    expect(is_file($path))->toBeTrue();
    $text = file_get_contents($path);
    expect($text)->toContain("TypeMap::register('GtkButton', \\Jovian\\Bindings\\Gtk\\Gtk\\GtkButton::class)")
        ->and($text)->toContain("TypeMap::lineage('GtkButton'");
});
